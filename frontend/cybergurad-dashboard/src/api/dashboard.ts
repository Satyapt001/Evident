import { API_BASE_URL } from '@/lib/constants'
import type { CategoryStat, RiskSlice, StatSummary, TimelinePoint } from '@/types/dashboard'
import type { Incident, IncidentStatus } from '@/types/incident'
import type { Severity, ThreatCategory } from '@/types/threat'

export interface DashboardResponse {
  total_events: number
  threats_detected: number
  critical_events: number
  active_incidents: number
  risk_distribution: Record<string, number>
  threat_distribution: Record<string, number>
  timeline: TimelinePoint[]
  recent_events: BackendIncidentEvent[]
  generated_at: string
}

interface BackendIncidentEvent {
  request_id: string
  event_id?: string | null
  threat_type: string
  risk_score: number
  risk_level: string
  confidence?: number | null
  explanation?: string
  indicators?: Array<Record<string, unknown>>
  source?: string
  metadata?: Record<string, unknown>
  timestamp?: string | null
  status?: string
}

export interface DashboardSnapshot {
  stats: StatSummary[]
  timeline: TimelinePoint[]
  risk: RiskSlice[]
  categories: CategoryStat[]
  incidents: Incident[]
  generatedAt: string
}

const API_ROOT = API_BASE_URL.replace(/\/$/, '')

async function getJson<T>(path: string): Promise<T> {
  const response = await fetch(`${API_ROOT}${path}`, {
    headers: { Accept: 'application/json' },
  })

  if (!response.ok) {
    let detail = `API request failed (${response.status})`
    try {
      const body = await response.json()
      if (typeof body?.detail === 'string') detail = body.detail
    } catch {
      // Keep the HTTP status message when the body is not JSON.
    }
    throw new Error(detail)
  }

  return response.json() as Promise<T>
}

function toSeverity(value: string): Severity {
  const normalized = value.toUpperCase()
  return ['SAFE', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'].includes(normalized)
    ? normalized as Severity
    : 'LOW'
}

function toCategory(value: string): ThreatCategory {
  const normalized = value.toUpperCase().replace(/_/g, ' ')
  if (normalized.includes('PHISH')) return 'PHISHING'
  if (normalized.includes('DEEPFAKE') || normalized.includes('IMPERSON')) return 'DEEPFAKE'
  if (normalized.includes('ACCOUNT') || normalized.includes('ATO')) return 'ACCOUNT TAKEOVER'
  if (normalized.includes('API')) return 'API ABUSE'
  if (normalized.includes('EXFIL')) return 'DATA EXFILTRATION'
  if (normalized.includes('URL')) return 'MALICIOUS URL'
  if (normalized.includes('NETWORK') || normalized.includes('PORT') || normalized.includes('DOS') || normalized.includes('BRUTE')) {
    return 'NETWORK ATTACK'
  }
  return 'NETWORK ATTACK'
}

function toStatus(value?: string): IncidentStatus {
  const normalized = value?.toUpperCase()
  return normalized === 'INVESTIGATING' || normalized === 'CONTAINED' || normalized === 'RESOLVED'
    ? normalized
    : 'OPEN'
}

function toIncident(event: BackendIncidentEvent): Incident {
  const category = toCategory(event.threat_type)
  const risk = toSeverity(event.risk_level)
  const detectedAt = event.timestamp ?? new Date().toISOString()
  const id = event.event_id ?? event.request_id

  return {
    id: `EVT-${id.slice(0, 12)}`,
    title: event.threat_type.replace(/_/g, ' '),
    category: risk === 'SAFE' ? 'NETWORK ATTACK' : category,
    source: event.source ?? 'Backend detector',
    risk: risk === 'SAFE' ? 'LOW' : risk,
    status: toStatus(event.status),
    detectedAt,
    assignee: 'SOC Queue',
    summary: event.explanation || 'Detection generated by a CyberGuard backend detector.',
  }
}

export async function getDashboardSnapshot(): Promise<DashboardSnapshot> {
  const data = await getJson<DashboardResponse>('/incidents/dashboard')

  const stats: StatSummary[] = [
    {
      key: 'events',
      label: 'TOTAL EVENTS',
      value: data.total_events,
      change: 0,
      upIsBad: false,
      caption: 'last 24h, backend events',
    },
    {
      key: 'threats',
      label: 'THREATS DETECTED',
      value: data.threats_detected,
      change: 0,
      upIsBad: true,
      caption: 'non-safe detections',
    },
    {
      key: 'critical',
      label: 'CRITICAL THREATS',
      value: data.critical_events,
      change: 0,
      upIsBad: true,
      caption: 'risk level = critical',
    },
    {
      key: 'incidents',
      label: 'ACTIVE INCIDENTS',
      value: data.active_incidents,
      change: 0,
      upIsBad: true,
      caption: 'open backend events',
    },
  ]

  const risk: RiskSlice[] = Object.entries(data.risk_distribution)
    .map(([level, count]) => ({ level: toSeverity(level), count }))
    .filter((item) => ['SAFE', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'].includes(item.level))

  const categories: CategoryStat[] = Object.entries(data.threat_distribution)
    .map(([category, count]) => ({ category: toCategory(category), count }))
    .reduce<CategoryStat[]>((acc, item) => {
      const existing = acc.find((entry) => entry.category === item.category)
      if (existing) existing.count += item.count
      else acc.push(item)
      return acc
    }, [])
    .sort((a, b) => b.count - a.count)

  return {
    stats,
    timeline: data.timeline,
    risk,
    categories,
    incidents: data.recent_events.map(toIncident),
    generatedAt: data.generated_at,
  }
}

export async function getIncidents(limit = 100): Promise<Incident[]> {
  const events = await getJson<BackendIncidentEvent[]>(`/incidents?limit=${limit}`)
  return events.map(toIncident)
}
