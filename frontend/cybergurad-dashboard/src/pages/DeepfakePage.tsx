import {  useMemo, useState } from 'react'
import { AlertTriangle, CheckCircle2, FileCheck2, ShieldAlert, ShieldCheck, UserRoundCheck } from 'lucide-react'
import PageHeader from '@/components/common/PageHeader'
import Panel from '@/components/common/Panel'
import { analyzeDeepfakeImage, executeDeepfakeAction, getDeepfakeActions } from '@/api/deepfake'

function pct(value: unknown) {
  const n = Number(value)
  return Number.isFinite(n) ? `${(n * 100).toFixed(2)}%` : '—'
}

function formatBytes(value: number) {
  if (!Number.isFinite(value)) return '—'
  if (value < 1024) return `${value} B`
  if (value < 1024 * 1024) return `${(value / 1024).toFixed(1)} KB`
  return `${(value / (1024 * 1024)).toFixed(2)} MB`
}

function levelClass(level: string) { return `deepfake-level deepfake-level--${String(level).toLowerCase()}` }

export default function DeepfakePage() {
  const [file, setFile] = useState<File | null>(null)
  const [result, setResult] = useState<any>(null)
  const [actions, setActions] = useState<any[]>([])
  const [caseState, setCaseState] = useState<any>(null)
  const [error, setError] = useState('')
  const [notice, setNotice] = useState('')
  const [busy, setBusy] = useState(false)
  const [actionBusy, setActionBusy] = useState('')

  const refreshActions = async (requestId: string) => {
    const data = await getDeepfakeActions(requestId)
    setActions(data.actions ?? [])
    setCaseState(data.case ?? null)
  }

  const submit = async () => {
    if (!file) return
    setBusy(true); setError(''); setNotice(''); setResult(null); setActions([]); setCaseState(null)
    try {
      const data = await analyzeDeepfakeImage(file)
      setResult(data)
      await refreshActions(data.request_id)
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Deepfake inference failed.')
    } finally { setBusy(false) }
  }

  const runAction = async (item: any) => {
    if (!result?.request_id || !item.available) return
    let approved = true
    if (item.requires_approval) {
      approved = window.confirm(`Confirm ${item.name}?\n\n${item.description}\n\nThis action changes the case state or media handling.`)
    }
    if (!approved) return
    setActionBusy(item.action_id); setError(''); setNotice('')
    try {
      const data = await executeDeepfakeAction(result.request_id, item.action_id, true, `Executed from DeepGuard admin console.`)
      if (data.status === 'APPROVAL_REQUIRED') { setNotice(data.message); return }
      setNotice(`${item.name} executed successfully.`)
      await refreshActions(result.request_id)
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Action failed.')
    } finally { setActionBusy('') }
  }

  const recommended = useMemo(() => actions.filter(action => action.recommended && action.available), [actions])
  const decisionActions = useMemo(() => actions.filter(action => ['CONFIRM_MANIPULATION', 'MARK_FALSE_POSITIVE', 'NEEDS_INVESTIGATION'].includes(action.action_id) && action.available), [actions])
  const risk = result?.risk ?? {}
  const model = result?.model ?? {}
  const media = result?.media ?? {}

  return <>
    <PageHeader title="DEEPFAKE / IMPERSONATION" telemetry={['DEEPGUARD MEDIA AUTHENTICITY ENGINE', 'DF40 · CLIP ViT-B/16']} />
    <Panel title="MEDIA ANALYSIS" subtitle="GENUINE DF40 INFERENCE · ADMIN-CONTROLLED RESPONSE">
      <div className="action-form">
        <input type="file" accept=".jpg,.jpeg,.png,.webp,.bmp" onChange={e => setFile(e.target.files?.[0] ?? null)} />
        <button className="btn btn--primary" disabled={!file || busy} onClick={() => void submit()}>{busy ? 'ANALYZING…' : 'ANALYZE MEDIA'}</button>
      </div>
      <p className="muted-note">The classifier result is generated by the supplied DF40 checkpoint. If inference fails, CyberGuard will not fabricate a prediction.</p>
      {error && <div className="action-error">{error}</div>}
      {notice && <div className="deepfake-notice"><CheckCircle2 size={16} />{notice}</div>}
    </Panel>

    {result && <>
      <Panel title="AUTHENTICITY VERDICT">
        <div className="deepfake-result-hero">
          <div className="deepfake-verdict">
            {model.predicted_class === 1 ? <ShieldAlert size={30} /> : <ShieldCheck size={30} />}
            <div><span>MEDIA ASSESSMENT</span><strong>{model.predicted_label === 'MANIPULATED' ? 'LIKELY MANIPULATED' : 'LIKELY AUTHENTIC'}</strong><p>{risk.severity_description}</p></div>
          </div>
          <div className={levelClass(risk.risk_level)}><span>SECURITY RISK</span><strong>{risk.risk_score ?? '—'}<small>/100</small></strong><b>{risk.risk_level ?? '—'}</b></div>
        </div>
        <div className="deepfake-kpi-grid">
          <div><span>MANIPULATION PROBABILITY</span><b>{pct(model.class_1_probability)}</b></div>
          <div><span>AUTHENTIC PROBABILITY</span><b>{pct(model.class_probabilities?.[0])}</b></div>
          <div><span>MODEL CONFIDENCE</span><b>{pct(model.confidence)}</b></div>
          <div><span>MODEL</span><b>DF40 CLIP ViT-B/16</b></div>
        </div>
      </Panel>

      <Panel title="ANALYSIS DETAILS">
        <div className="deepfake-detail-grid">
          <div><span>FILE</span><b>{result.filename}</b></div>
          <div><span>MEDIA FORMAT</span><b>{media.format}</b></div>
          <div><span>RESOLUTION</span><b>{media.width} × {media.height}</b></div>
          <div><span>FILE SIZE</span><b>{formatBytes(Number(media.size_bytes))}</b></div>
          <div><span>DEVICE</span><b>{model.device}</b></div>
          <div><span>ANALYSIS ID</span><b>{result.request_id}</b></div>
        </div>
        <div className="deepfake-hash"><span>INPUT SHA-256</span><code>{media.sha256}</code></div>
      </Panel>

      <Panel title="MODEL-DERIVED EVIDENCE" subtitle="Only values actually computed by the model or input-processing pipeline are shown.">
        <div className="deepfake-evidence-grid">
          {(result.analysis_evidence ?? []).map((item: any) => <div className="deepfake-evidence-card" key={item.name}>
            <span>{item.name}</span><strong>{typeof item.value === 'number' && item.unit === '%' ? `${item.value.toFixed(2)}%` : String(item.value)}</strong><small>{item.unit}</small><p>{item.interpretation}</p>
          </div>)}
        </div>
        <div className="deepfake-probability-bar"><div><span>AUTHENTIC</span><b>{pct(model.class_probabilities?.[0])}</b></div><div><span>MANIPULATED</span><b>{pct(model.class_1_probability)}</b></div></div>
      </Panel>

      <Panel title="SECURITY ASSESSMENT">
        <div className="deepfake-assessment"><AlertTriangle size={18} /><div><b>{risk.risk_level} PRIORITY</b><p>{risk.severity_description}</p><p>Model confidence and security risk are displayed separately. The risk score is derived from the trained classifier probability and the existing deepfake risk policy.</p></div></div>
      </Panel>

      <Panel title="RECOMMENDED ADMIN ACTIONS" subtitle="Recommendations do not execute automatically. The administrator chooses each action.">
        {recommended.length ? <div className="deepfake-action-grid">{recommended.map(item => <div className={`deepfake-action-card ${item.requires_approval ? 'is-approval' : ''}`} key={item.action_id}>
          <div><b>{item.name}</b><span>{item.priority} PRIORITY {item.requires_approval ? '· APPROVAL REQUIRED' : ''}</span><p>{item.description}</p></div>
          <button className={item.requires_approval ? 'btn btn--danger' : 'btn'} disabled={actionBusy === item.action_id} onClick={() => void runAction(item)}>{actionBusy === item.action_id ? 'EXECUTING…' : item.name.toUpperCase()}</button>
        </div>)}</div> : <div className="deepfake-empty">No immediate admin action is recommended for this result.</div>}
        <div className="deepfake-all-actions"><span>AVAILABLE CONTROLS</span>{actions.filter(a => !a.recommended && a.available).map(item => <button className="btn btn--small" key={item.action_id} disabled={actionBusy === item.action_id} onClick={() => void runAction(item)}>{item.name}</button>)}</div>
      </Panel>

      <Panel title="ANALYST DECISION">
        <div className="deepfake-decision"><UserRoundCheck size={18} /><div><b>Separate the analyst decision from the model prediction.</b><p>The model remains unchanged; this records the administrator's final disposition.</p></div></div>
        <div className="deepfake-decision-grid">{decisionActions.map(item => <button className="btn" key={item.action_id} disabled={actionBusy === item.action_id} onClick={() => void runAction(item)}>{item.name}</button>)}</div>
        {caseState?.analyst_decision && <div className="deepfake-notice"><FileCheck2 size={16} />Analyst decision: {caseState.analyst_decision}</div>}
      </Panel>

      <Panel title="ACTION / AUDIT HISTORY">
        <div className="deepfake-audit">{caseState?.actions?.length ? caseState.actions.slice().reverse().map((item: any, index: number) => <div key={`${item.timestamp}-${index}`}><span>{new Date(item.timestamp).toLocaleString()}</span><b>{item.name}</b><small>{item.status} · {item.actor}</small>{item.note && <p>{item.note}</p>}</div>) : <div className="deepfake-empty">No administrator actions have been executed yet.</div>}</div>
      </Panel>
    </>}
  </>
}
